"""Extract source-certified equipment and full-set references without running hooks."""

from __future__ import annotations
import argparse
import json
from pathlib import Path
from generate_native_hit_status import decode
from native_hit_status_analysis import Instruction
from native_equipment_fact_analysis import equipment_facts, armor_set_facts

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "ModSources/InfiniCrafterLocal/Common/Services/Generation/NativeEquipmentFactsCatalog.g.cs"
REPORT = ROOT / "contracts/reports/native_equipment_sources.generated.json"


def extended_decode(path, method):
    import dnfile

    result = list(decode(path, "Player", method, "Terraria.ID.ItemID"))
    pe = dnfile.dnPE(str(path))
    fields, booleans = {}, set()
    for t in pe.net.mdtables.TypeDef:
        owner = str(t.TypeNamespace) + "." + str(t.TypeName)
        for f in t.FieldList:
            fields[id(f.row)] = owner + "." + str(f.row.Name)
            if f.row.Signature.value == b"\x06\x02":
                booleans.add(fields[id(f.row)])
    code = []
    for i in result[0]:
        arg = i.arg
        if i.op == "stfld":
            row = pe.net.mdtables.Field.rows[(arg.value & 0xFFFFFF) - 1]
            arg = fields[id(row)]
            if row.Signature.value == b"\x06\x02":
                arg += ":bool"
        elif i.op in ("ldfld", "ldsfld") and arg in booleans:
            arg += ":bool"
        elif i.op == "ldstr":
            arg = str(pe.net.user_strings.get(arg.value & 0xFFFFFF).value)
        code.append(Instruction(i.offset, i.op, arg))
    result[0] = code
    return result


def extract(path):
    sources = []
    for method, analyze in [("GrantArmorBenefits", equipment_facts), ("UpdateArmorSets", armor_set_facts)]:
        code, ids, _, version, sha, assembly, module = extended_decode(path, method)
        records = analyze(code)
        if method == "GrantArmorBenefits":
            names = {v: k for k, v in ids.items() if k not in ("None", "Count")}
            for r in records:
                r["fullName"] = "Terraria/" + names[r["itemId"]]
        sources.append(
            {
                "method": "Player." + method,
                "assemblyVersion": version,
                "sourceMethodSha256": sha,
                "sourceModuleVersionId": module,
                "assemblySha256": assembly,
                "records": records,
            }
        )
    return sources


def render(sources):
    lines = [
        "// Generated by tools/generate/generate_native_equipment_facts.py; do not hand-edit.",
        "using System.Collections.Generic;",
        "",
        "namespace InfiniCrafterLocal.Common.Services;",
        "",
        "internal static class NativeEquipmentFactsCatalog",
        "{",
        "    internal static readonly Dictionary<string, string> Sources = new()",
        "    {",
    ]
    for s in sorted(sources, key=lambda x: x["method"] + x["sourceMethodSha256"]):
        key = s["method"] + ":" + s["sourceMethodSha256"] + ":" + s["sourceModuleVersionId"]
        value = json.dumps(s["records"], separators=(",", ":"))
        lines.append(f'        ["{key}"] = """{value}""",')
    return "\n".join(lines + ["    };", "}", ""])


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--assembly", type=Path, action="append", required=True)
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    sources = [s for path in a.assembly for s in extract(path)]
    for path, text in {
        OUTPUT: render(sources),
        REPORT: json.dumps({"schema": "infini.native-equipment-sources.v1", "sources": sources}, indent=2) + "\n",
    }.items():
        if a.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit("Stale source facts: " + str(path))
        else:
            path.write_text(text)
    for s in sources:
        print(s["method"], len(s["records"]), "recognized source branches")


if __name__ == "__main__":
    main()
