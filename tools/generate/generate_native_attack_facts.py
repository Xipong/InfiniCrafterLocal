"""Generate narrow source-certified shooting and line-collision observations.

Uses the same nonexecuting assembly decoder and certificate conventions as the
NPC-status facts. No item-name routing, runtime hook execution or native AI VM.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from generate_native_hit_status import decode
from native_attack_fact_analysis import shoot_facts, line_collision_facts

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "ModSources/InfiniCrafterLocal/Common/Services/Generation/NativeAttackFactsCatalog.g.cs"
REPORT = ROOT / "contracts/reports/native_attack_sources.generated.json"


def extract(path):
    sources = []
    for owner, method, ids, analyze in (
        ("Player", "ItemCheck_Shoot", "ItemID", shoot_facts),
        ("Projectile", "Colliding", "ProjectileID", line_collision_facts),
    ):
        code, constants, _, version, method_hash, assembly_hash, module = decode(path, owner, method, "Terraria.ID." + ids)
        names = {value: name for name, value in constants.items() if name not in ("Count", "None")}
        records = analyze(code)
        for record in records:
            record["fullName"] = "Terraria/" + names[record.get("itemId", record.get("projectileId"))]
        sources.append({"method": owner + "." + method, "assemblyVersion": version,
            "sourceMethodSha256": method_hash, "sourceModuleVersionId": module, "assemblySha256": assembly_hash,
            "records": records})
    return sources


def render(sources):
    lines = ["// Generated by tools/generate/generate_native_attack_facts.py; do not hand-edit.",
        "using System.Collections.Generic;", "", "namespace InfiniCrafterLocal.Common.Services;", "",
        "internal static class NativeAttackFactsCatalog", "{",
        "    internal static readonly Dictionary<string, Dictionary<int, string>> Sources = new()", "    {"]
    for source in sorted(sources, key=lambda s: s["method"] + s["sourceMethodSha256"]):
        key = source["method"] + ":" + source["sourceMethodSha256"] + ":" + source["sourceModuleVersionId"]
        lines += [f'        ["{key}"] = new()', "        {"]
        for row in source["records"]:
            identity = row.get("itemId", row.get("projectileId"))
            contents = json.dumps(row, separators=(",", ":"))
            lines.append(f'            [{identity}] = """{contents}""",')
        lines += ["        },"]
    return "\n".join(lines + ["    };", "}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assembly", type=Path, action="append", required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    sources = [s for assembly in args.assembly for s in extract(assembly)]
    products = {OUTPUT: render(sources), REPORT: json.dumps({"schema": "infini.native-attack-sources.v1", "sources": sources}, indent=2) + "\n"}
    for path, text in products.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                raise SystemExit("stale generated source facts: " + str(path))
        else:
            path.write_text(text, encoding="utf-8")
    for source in sources:
        print(source["method"], len(source["records"]), "recognized source branches")


if __name__ == "__main__":
    main()
