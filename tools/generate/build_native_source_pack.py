#!/usr/bin/env python3
"""Pin source projections, then generate the complete native source pack offline.

Use --build with the target's tModLoader/decompiler dependencies for the complete
bootstrap/generation flow. Alternatively run --refresh-pin before compiling a
harness, then pass --harness. Rebuild the shipping target afterwards to copy the
generated asset. --check validates the source fingerprint and actual ZIP bytes.
No SDK, game, model, mod catalog download or network access is performed here.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[2]
MOD = ROOT / "mod/InfiniCrafterLocal"
PIN = MOD / "Common/Services/Generation/NativeSourcePackBuild.g.cs"
OUTPUT = MOD / "Data/native-source-pack.zip"


def projection_fingerprint() -> tuple[str, int]:
    """Frame exact bytes with 8-byte big-endian lengths; no newline rewriting."""
    paths = sorted(MOD.rglob("GeneratorClient*.cs"), key=lambda path: path.relative_to(ROOT).as_posix())
    if not paths:
        raise ValueError("No canonical GeneratorClient source files found")
    digest = hashlib.sha256(b"ifc-native-source-projections-v1\0")
    for path in paths:
        name = path.relative_to(ROOT).as_posix().encode("utf-8")
        content = path.read_bytes()
        digest.update(len(name).to_bytes(8, "big"))
        digest.update(name)
        digest.update(len(content).to_bytes(8, "big"))
        digest.update(content)
    return digest.hexdigest(), len(paths)


def render_pin(fingerprint: str) -> str:
    return (
        "// Generated by tools/generate/build_native_source_pack.py --refresh-pin; do not hand-edit.\n"
        "namespace InfiniCrafterLocal.Common.Services;\n\n"
        "internal static class NativeSourcePackBuild\n{\n"
        f'    internal const string ProjectionSha256 = "{fingerprint}";\n'
        "}\n"
    )


def check_pin(fingerprint: str) -> None:
    if not PIN.is_file() or PIN.read_bytes() != render_pin(fingerprint).encode("utf-8"):
        raise ValueError("Native source projection fingerprint is stale; run --refresh-pin before rebuilding the harness and pack")


def file_hash(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def check_pack(path: Path, fingerprint: str, native: Path | None = None) -> dict:
    with zipfile.ZipFile(path) as archive:
        metadata = archive.getinfo("manifest.json")
        if metadata.file_size > 4 * 1024 * 1024:
            raise ValueError("Native source pack manifest exceeds the runtime bound")
        manifest = json.loads(archive.read(metadata))
        if manifest.get("version") != 1 or manifest.get("minimumMethodIlBytes") != 2048:
            raise ValueError("Native source pack schema differs from the runtime contract")
        if manifest.get("projectionSha256") != fingerprint:
            raise ValueError("Native source pack was built from different source projections")
        if manifest.get("decompilerSha256") != file_hash(MOD / "lib/ICSharpCode.Decompiler.dll"):
            raise ValueError("Native source pack decompiler bytes differ from the bundled dependency")
        if native is not None and manifest.get("nativeAssemblySha256") != file_hash(native):
            raise ValueError("Native source pack tModLoader bytes differ from the selected target")
        rows = manifest.get("entries")
        if not isinstance(rows, list) or not 1 <= len(rows) <= 30000:
            raise ValueError("Native source pack has no valid entry index")
        names = [row["key"] + ".json" for row in rows]
        if (len(names) != len(set(names)) or len(archive.infolist()) != len(rows) + 1
                or set(archive.namelist()) != {"manifest.json", *names}):
            raise ValueError("Native source pack archive entries differ from its index")
        for row, name in zip(rows, names):
            entry = archive.getinfo(name)
            if not 0 < entry.file_size <= 4 * 1024 * 1024 or entry.file_size != row["bytes"]:
                raise ValueError("Native source pack entry length differs from its index")
            if hashlib.sha256(archive.read(entry)).hexdigest() != row["sha256"]:
                raise ValueError("Native source pack entry bytes differ from its index")
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--refresh-pin", action="store_true", help="Refresh the generated fingerprint before the bootstrap build")
    mode.add_argument("--check", action="store_true", help="Verify source fingerprint and the complete generated pack index/bytes")
    mode.add_argument("--build", action="store_true", help="Refresh pin, bootstrap the harness, and generate the target's complete pack")
    mode.add_argument("--harness", type=Path, help="Already built EngineRuntimeChecks.dll using the current fingerprint")
    parser.add_argument("--dotnet", default=os.environ.get("DOTNET", "dotnet"))
    parser.add_argument("--runtime-dotnet", type=Path, help="Exact private tML runtime host used for collection, separate from the build SDK")
    parser.add_argument("--runtimeconfig", type=Path, help="Official tModLoader.runtimeconfig.json; collection disables framework roll-forward")
    parser.add_argument("--target-rid", help="Exact target RID, for example win-x64 or linux-x64; selects official managed runtime assets")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--tml-references", type=Path, default=os.environ.get("INFINI_TML_REFERENCE_DIR"))
    parser.add_argument("--external-deps", type=Path, default=os.environ.get("INFINI_TML_DEPS_SRC"))
    parser.add_argument("--harness-output", type=Path, default=ROOT / "artifacts/native-source-pack-harness")
    args = parser.parse_args()
    try:
        fingerprint, count = projection_fingerprint()
        if args.refresh_pin or args.build:
            PIN.write_bytes(render_pin(fingerprint).encode("utf-8"))
        if args.refresh_pin:
            print(json.dumps({"status": "pin_refreshed", "projectionSha256": fingerprint, "sourceFiles": count}), flush=True)
            return 0
        check_pin(fingerprint)
        if args.check:
            native = args.tml_references / "tModLoader.dll" if args.tml_references is not None else None
            manifest = check_pack(args.output, fingerprint, native)
            print(json.dumps({"status": "current", "projectionSha256": fingerprint, "sourceFiles": count,
                              "packSha256": file_hash(args.output), "entries": len(manifest["entries"])}))
            return 0
        staging_command = None
        if args.runtime_dotnet is not None or args.runtimeconfig is not None or args.target_rid is not None:
            if args.runtime_dotnet is None or args.runtimeconfig is None or args.target_rid is None:
                raise ValueError("Pass --runtime-dotnet, --runtimeconfig and --target-rid together for an exact tML target")
            runtime_config = args.runtimeconfig.resolve(strict=True)
            stage_output = args.harness_output.resolve() if args.build else args.harness.resolve(strict=True).parent
            target_references = stage_output.with_name(stage_output.name + "-references")
            staging_command = [sys.executable, str(ROOT / "tools/build/stage_tml_references.py"),
                               "--runtime", str(runtime_config.parent), "--rid", args.target_rid,
                               "--destination", str(target_references)]
            subprocess.run(staging_command, cwd=ROOT, check=True)
            if args.tml_references is not None and file_hash(args.tml_references / "tModLoader.dll") != file_hash(target_references / "tModLoader.dll"):
                raise ValueError("Official runtime tModLoader bytes differ from the selected build references")
            args.tml_references = target_references
        if args.build:
            if args.tml_references is None or args.external_deps is None:
                raise ValueError("--build requires --tml-references and --external-deps (or their INFINI_TML environment variables)")
            references = args.tml_references.resolve(strict=True)
            dependencies = args.external_deps.resolve(strict=True)
            for file in (references / "tModLoader.dll", dependencies / "ParticleLibrary/ParticleLibrary.dll",
                         dependencies / "Luminance/bin/Debug/net8.0/Luminance.dll"):
                if not file.is_file():
                    raise ValueError(f"Missing native build input: {file}")
            harness_output = args.harness_output.resolve()
            subprocess.run([args.dotnet, "build", str(ROOT / "tests/native/EngineRuntimeChecks.csproj"),
                            "--configuration", "Release", "--output", str(harness_output),
                            f"-p:InfiniTmlReferenceDir={references}", f"-p:InfiniExternalDepsRoot={dependencies}"],
                           cwd=ROOT, check=True)
            args.harness = harness_output / "EngineRuntimeChecks.dll"
        harness = args.harness.resolve(strict=True)
        if staging_command is not None:
            subprocess.run([*staging_command, "--harness", str(harness)], cwd=ROOT, check=True)
        output = args.output.resolve()
        output.parent.mkdir(parents=True, exist_ok=True)
        harness_hash = file_hash(harness)
        native_hash = file_hash(harness.parent / "tModLoader.dll")
        decompiler_hash = file_hash(harness.parent / "ICSharpCode.Decompiler.dll")
        command = [args.dotnet, str(harness), "--build-native-source-pack", str(output)]
        environment = os.environ.copy()
        # The build enumerates all identities and has its own bounded progress
        # receipts. Per-method tracing belongs to the fresh performance cohorts.
        environment["INFINI_PARENT_ANALYSIS_PROFILE"] = "0"
        launch = None
        if args.runtime_dotnet is not None or args.runtimeconfig is not None:
            if args.runtime_dotnet is None or args.runtimeconfig is None:
                raise ValueError("Pass --runtime-dotnet and --runtimeconfig together for an exact tML runtime launch")
            runtime_host = args.runtime_dotnet.resolve(strict=True)
            runtime_config = args.runtimeconfig.resolve(strict=True)
            config = json.loads(runtime_config.read_text(encoding="utf-8-sig"))
            framework = config["runtimeOptions"]["framework"]
            if framework.get("name") != "Microsoft.NETCore.App" or not isinstance(framework.get("version"), str):
                raise ValueError("Expected the official tML Microsoft.NETCore.App framework version")
            command = [str(runtime_host), "exec", "--runtimeconfig", str(runtime_config),
                       "--roll-forward", "Disable", str(harness), "--build-native-source-pack", str(output)]
            environment["DOTNET_ROOT"] = str(runtime_host.parent)
            environment["DOTNET_ROOT_X64"] = str(runtime_host.parent)
            environment["DOTNET_MULTILEVEL_LOOKUP"] = "0"
            environment["DOTNET_ROLL_FORWARD"] = "Disable"
            launch = {"runtimeDotnetSha256": file_hash(runtime_host), "runtimeconfigSha256": file_hash(runtime_config),
                      "runtimeVersion": framework["version"], "runtimeIdentifier": args.target_rid,
                      "targetStagingSha256": file_hash(harness.parent / "native-target-staging.json"), "rollForward": "Disable"}
            subprocess.run([*command[:-2], "--verify-native-target", str(harness.parent / "native-target-staging.json")],
                           cwd=ROOT, env=environment, check=True)
        subprocess.run(command, cwd=ROOT, env=environment, check=True)
        report_path = Path(str(output) + ".report.json")
        report = json.loads(report_path.read_text(encoding="utf-8-sig"))
        expected = {
            "status": "complete", "projectionSha256": fingerprint,
            "collectorAssemblySha256": harness_hash, "nativeAssemblySha256": native_hash,
            "decompilerAssemblySha256": decompiler_hash, "packSha256": file_hash(output),
        }
        for key, value in expected.items():
            if report.get(key) != value:
                raise ValueError(f"Generated pack input mismatch for {key}: expected {value!r}, got {report.get(key)!r}")
        if launch is not None:
            if report.get("runtimeVersion") != launch["runtimeVersion"]:
                raise ValueError("Collector did not execute under the exact official tML runtime version")
            report["collectorLaunch"] = launch
            report_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        # No successful command may hide skipped/failed identities.
        identities = report.get("identities", [])
        if report.get("errors") != [] or len(identities) != report["projectileCount"] + report["itemCount"]:
            raise ValueError("Generated pack did not visit the complete native identity ranges")
        for kind, total in (("projectile", report["projectileCount"]), ("item", report["itemCount"])):
            found = [row["type"] for row in identities if row["kind"] == kind]
            if sorted(found) != list(range(1, total + 1)):
                raise ValueError(f"Generated pack has missing/duplicate {kind} identities")
        current_fingerprint, _ = projection_fingerprint()
        if current_fingerprint != fingerprint:
            raise ValueError("Source projections changed during pack generation; regenerate against a stable source tree")
        check_pack(output, fingerprint, harness.parent / "tModLoader.dll")
        print(json.dumps({"status": "complete", "output": str(output), "report": str(report_path),
                          "projectionSha256": fingerprint, "packSha256": expected["packSha256"],
                          "projectileCount": report["projectileCount"], "itemCount": report["itemCount"]}))
        return 0
    except (OSError, ValueError, KeyError, TypeError, subprocess.SubprocessError, zipfile.BadZipFile) as error:
        print(f"native source pack: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
