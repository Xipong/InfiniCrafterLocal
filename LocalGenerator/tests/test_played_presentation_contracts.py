def _silver_delivery(wire_transport, monkeypatch):
    data = compile_runtime_program(build_runtime_fixture("workbench_blade"))
    # CPU contract fixture identity/path only, not an image-generation result.
    data.update(id="fixture_played_silver", schemaVersion=5,
                runtimeApiVersion="infini.runtime-program.v5", sourceMode="test_fixture")
    before = copy.deepcopy(data)
    kit = _visual_kit(data)
    kit["item"].update(palette=["copper with silver highlights"])
    responses, requests = wire_transport
    responses.append(kit)
    data = visual.apply_visual_director(data, {}, {})
    data["visual"].update(spritePath="fixture_played_silver.png", spriteStatus="generated")
    raw = _sprite(data)
    silver = {"r": 192, "g": 192, "b": 192}
    raw["slots"][0]["element"]["colorProfile"].update(start=silver, middle=silver, end=silver)
    particle = _library_particle(data)["slots"][0]
    particle["particle"].update(colorStart=silver, colorEnd=silver)
    raw["slots"].append(particle)
    responses.append(raw)
    final = vfx.attach_vfx_manifest(data, "silver-tracer", llm_director=stage.call_llm_vfx_director)
    # Exercise the real post-image projection without claiming generated bytes:
    # this fixture has only item/reused bodies, so no extra image job is needed.
    from infini_local.pipelines import visual_sprite_generation as images
    monkeypatch.setattr(images, "maybe_generate_sprite", lambda value: value)
    monkeypatch.setattr(images, "write_visual_manifest", lambda value, plan: None)
    final = images.maybe_generate_visual_assets(final)
    delivered = sanitize_recipe_for_delivery(final)
    assert "effectColor" not in delivered["visual"]
    assert delivered["visual"]["palette"] == ["copper with silver highlights"]
    slots = delivered["vfxManifest"]["slots"]
    assert slots[0]["element"]["colorProfile"] == dict(start=silver, middle=silver, end=silver, curve="linear")
    assert slots[1]["particle"]["colorStart"] == silver
    assert slots[1]["particle"]["colorEnd"] == silver
    assert validate_runtime_wire(delivered)["ok"]
    assert vfx.validate_vfx_manifest_wire(delivered)["ok"]
    assert delivered["gameplay"] == before["gameplay"]
    assert [r["_infini_stage"] for r in requests] == ["visual_director", "vfx_director"]
    assert not responses
    return delivered


def test_silver_survives_visual_vfx_and_final_delivery_without_gray_repair(wire_transport, monkeypatch):
    _silver_delivery(wire_transport, monkeypatch)


def test_native_silver_fixture_is_actual_final_delivery(wire_transport, monkeypatch):
    import json
    from pathlib import Path
    fixture = Path(__file__).resolve().parents[2] / "tools/fixtures/played-silver-delivered.json"
    saved = json.loads(fixture.read_text(encoding="utf-8"))
    current = _silver_delivery(wire_transport, monkeypatch)
    # This retained native witness now uses current RGB, but its authored report
    # and diagnostic snapshots still record the historical provider response.
    # Preserve those bytes; compare every non-diagnostic delivered field exactly.
    from infini_local.core.runtime_authoring.program_schema import realization_schema
    assert strict_schema_errors(saved["realization"], realization_schema())
    assert not strict_schema_errors(current["realization"], realization_schema())
    assert isinstance(saved["realization"]["selfEvaluation"], dict)
    assert isinstance(current["realization"]["selfEvaluation"], str)
    projected = copy.deepcopy(saved)
    projected["realization"]["selfEvaluation"] = current["realization"]["selfEvaluation"]
    for key in ("visualDirectorRaw", "vfxDirectorRaw"):
        assert key in saved["debug"] and key in current["debug"]
        projected["debug"][key] = current["debug"][key]
    assert projected == current


