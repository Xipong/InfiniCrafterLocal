def test_all_rendering_color_schema_branches_share_closed_local_rgb():
    from infini_local.core.vfx.materials import rgb_schema, element_schema, library_particle_schema, path_schema
    assert "effectColor" not in visual_contract._visual_item_schema()["properties"]
    rgb = rgb_schema()
    for schema in (element_schema(), path_schema()):
        for knot in ("start", "middle", "end"):
            assert schema["properties"]["colorProfile"]["properties"][knot] == rgb
    for endpoint in ("colorStart", "colorEnd"):
        assert library_particle_schema()["properties"][endpoint] == rgb
    assert not strict_schema_errors({"r": 192, "g": 192, "b": 192}, rgb)
    assert strict_schema_errors("silver", rgb)
    assert strict_schema_errors("effect", rgb)


@pytest.mark.parametrize("repair", [False, True])
@pytest.mark.parametrize("draw,entity_scale", [(1, 1), (4, 4), (.1, .25)])
def test_serialized_visual_packet_preserves_hand_geometry_without_moving_collision(wire_transport, repair, draw, entity_scale):
    data = compile_runtime_program(build_runtime_fixture("workbench_blade"))
    body = next(e for e in data["runtimeProgram"]["entities"] if e["kind"] == "owner_attached_projectile")
    body["hitbox"]["drawScale"] = draw
    body.setdefault("visual", {})["scale"] = entity_scale
    before = copy.deepcopy(data)
    errors = [{"path": "$.item.renderSizePx", "message": "invalid"}] if repair else None
    # Capture the actual transport request; no model or image generation.
    responses, requests = wire_transport
    responses.append({})
    visual_request._request_visual_kit(data, {}, {}, repair_errors=errors, previous={} if repair else None)
    assert body["hitbox"]["drawScale"] == draw and body["visual"]["scale"] == entity_scale
    runtime_rows = request_dossier(requests[0])["runtimeEntitiesReadOnly" if repair else "runtimeEntities"]
    runtime_body = next(row for row in runtime_rows if row["id"] == body["id"])
    for member in ("aim", "attachment", "reach", "rotation", "hitbox"):
        assert runtime_body[member] == body[member]
    assert data == before


def test_retained_umbrella_body_is_unchanged_in_explicit_current_visibility_control():
    import json
    from pathlib import Path
    fixture = Path(__file__).resolve().parents[2] / "tools/fixtures/played-umbrellas-delivered.json"
    rows = json.loads(fixture.read_text(encoding="utf-8"))
    assert {row["id"] for row in rows} == {"g_a68f03dee9621149", "g_60d18fd7593d52d8", "g_9e339be4540919d3"}
    before = copy.deepcopy(rows)
    for row in rows:
        report = validate_runtime_wire(row)
        assert not report["ok"] and any(e["path"] == "$.runtimeProgram.itemUse.releaseTiming" for e in report["errors"])
        control = copy.deepcopy(row)
        assert control["gameplay"].pop("releaseTiming") == "immediate"
        assert control["runtimeProgram"]["itemUse"].pop("releaseTiming") == "immediate"
        assert control["runtimeProgram"]["itemUse"]["hideUseGraphic"] is True
        assert validate_runtime_wire(control)["ok"]
        assert control["runtimeProgram"]["entities"] == row["runtimeProgram"]["entities"]
        assert control["visual"] == row["visual"]
        assert vfx_validation.validate_vfx_manifest_wire(control)["ok"]
        entity = next(e for e in row["runtimeProgram"]["entities"] if e["id"] == row["runtimeProgram"]["primaryEntityId"])
        assert entity["movement"] == dict(code=20, name="move_front_hand", params=dict(aimMode="initial", durationTicks=13, hitboxOffsetPx=24, peakStretch="full", startStretch="none"))
        assert entity["hitbox"] == dict(drawScale=1, heightPx=30, hitboxScale=1, widthPx=30)
        assert row["visual"]["renderSizePx"] == 54
        assert row["visual"]["grip"] == dict(normalizedX=.1875, normalizedY=.5)
        if row["id"] == "g_9e339be4540919d3":
            assert [e["action"] for e in entity["events"]] == ["spawn_entity_on_event"]
            assert entity["events"][0]["count"] == 1

    assert rows == before
