def test_all_rendering_color_schema_branches_share_closed_local_rgb():
    from infini_local.core.vfx_material_contract import rgb_schema, element_schema, library_particle_schema, path_schema
    assert "effectColor" not in visual._visual_item_schema()["properties"]
    rgb = rgb_schema()
    for schema in (element_schema(), path_schema()):
        for knot in ("start", "middle", "end"):
            assert schema["properties"]["colorProfile"]["properties"][knot] == rgb
    for endpoint in ("colorStart", "colorEnd"):
        assert library_particle_schema()["properties"][endpoint] == rgb
    assert not strict_schema_errors({"r": 192, "g": 192, "b": 192}, rgb)
    assert strict_schema_errors("silver", rgb)
    assert strict_schema_errors("effect", rgb)


