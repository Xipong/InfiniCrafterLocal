@pytest.mark.parametrize("repair", [False, True])
@pytest.mark.parametrize("draw,entity_scale", [(1, 1), (4, 4), (.1, .25)])
def test_serialized_visual_packet_explains_hand_extent_without_moving_collision(wire_transport, repair, draw, entity_scale):
    data = compile_runtime_program(build_runtime_fixture("workbench_blade"))
    body = next(e for e in data["runtimeProgram"]["entities"] if e["kind"] == "owner_attached_projectile")
    body["hitbox"]["drawScale"] = draw
    body.setdefault("visual", {})["scale"] = entity_scale
    before = copy.deepcopy(data)
    errors = [{"path": "$.item.renderSizePx", "message": "invalid"}] if repair else None
    # Capture the actual transport request; no model or image generation.
    responses, requests = wire_transport
    responses.append({})
    visual._request_visual_kit(data, {}, {}, repair_errors=errors, previous={} if repair else None)
    presentation = request_dossier(requests[0])["spritePresentationReadOnly"]
    geometry = presentation["handContactGeometry"]
    assert "6px" in geometry
    assert "hitboxOffsetPx does not extend the visible body" in geometry
    assert "signed distance from grip to the authored contact region" in geometry
    assert "effective multiplier from formulas.body" in geometry
    assert "clamp(P, .1, 8)" in geometry
    assert "explicit curve/mirror exception" in geometry
    assert "R/C and current P" not in geometry
    assert body["hitbox"]["drawScale"] == draw and body["visual"]["scale"] == entity_scale
    assert "never move only the picture to pretend to extend collision reach" in geometry
    assert data == before


def test_retained_played_umbrella_geometry_is_admitted_without_reauthoring():
    import json
    from pathlib import Path
    fixture = Path(__file__).resolve().parents[2] / "tools/fixtures/played-umbrellas-delivered.json"
    rows = json.loads(fixture.read_text(encoding="utf-8"))
    assert {row["id"] for row in rows} == {"g_a68f03dee9621149", "g_60d18fd7593d52d8", "g_9e339be4540919d3"}
    for row in rows:
        assert validate_runtime_wire(row)["ok"]
        assert vfx.validate_vfx_manifest_wire(row)["ok"]
        entity = next(e for e in row["runtimeProgram"]["entities"] if e["id"] == row["runtimeProgram"]["primaryEntityId"])
        assert entity["movement"] == dict(code=20, name="move_front_hand", params=dict(aimMode="initial", durationTicks=13, hitboxOffsetPx=24, peakStretch="full", startStretch="none"))
        assert entity["hitbox"] == dict(drawScale=1, heightPx=30, hitboxScale=1, widthPx=30)
        assert row["visual"]["renderSizePx"] == 54
        assert row["visual"]["grip"] == dict(normalizedX=.1875, normalizedY=.5)
        if row["id"] == "g_9e339be4540919d3":
            assert [e["action"] for e in entity["events"]] == ["spawn_entity_on_event"]
            assert entity["events"][0]["count"] == 1
