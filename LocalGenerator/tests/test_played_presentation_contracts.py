def test_all_rendering_color_schema_branches_share_the_same_finite_tokens():
    from infini_local.core.vfx_material_contract import COLOR_TOKENS, element_schema, library_particle_schema, path_schema
    visual_tokens = visual._visual_item_schema()["properties"]["effectColor"]["enum"]
