from __future__ import annotations

"""Runtime dump discovery and lookup helpers.

Runtime dumps are optional JSONL files generated by the in-game /infinidump command.
They belong outside server.py because they are pure data-discovery/indexing logic, not
HTTP/combine orchestration.
"""

from pathlib import Path
from typing import Any

from infini_local.core.config_bootstrap import DATA_DIR
from infini_local.core import strict_json
from infini_local.core.env_utils import env_first, env_str


def runtime_dump_candidates(data_dir: Path, filename: str, explicit_env: str, legacy_env: str) -> list[Path]:
    candidates: list[Path] = []
    explicit = env_first((explicit_env, legacy_env), "")
    if explicit:
        candidates.append(Path(explicit))

    # Optional packaged/dev location, useful while hacking locally, but should not
    # be populated in normal public zips.
    candidates.append(data_dir / "runtime_dumps" / filename)

    home = Path.home()
    user_profile = Path(env_str("USERPROFILE", str(home)))
    docs_roots = [
        home / "Documents",
        user_profile / "Documents",
        user_profile / "OneDrive" / "Documents",
        user_profile / "OneDrive" / "Документы",
        home / "Документы",
    ]
    for docs in docs_roots:
        candidates.append(docs / "My Games" / "Terraria" / "tModLoader" / "InfiniCrafterLocal" / filename)

    out: list[Path] = []
    seen: set[str] = set()
    for c in candidates:
        key = str(c).lower()
        if key not in seen:
            seen.add(key)
            out.append(c)
    return out


def resolve_runtime_dump_path(data_dir: Path, filename: str, explicit_env: str, legacy_env: str) -> Path:
    candidates = runtime_dump_candidates(data_dir, filename, explicit_env, legacy_env)
    for c in candidates:
        if c.exists():
            return c
    return candidates[0]


def load_jsonl_index(path: Path) -> tuple[list[dict[str, Any]], dict[Any, dict[str, Any]]]:
    rows: list[dict[str, Any]] = []
    by_type: dict[Any, dict[str, Any]] = {}
    try:
        if not path.exists():
            return rows, by_type
        with path.open("rb") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    row = strict_json.loads(line.decode("utf-8-sig"))
                except Exception:
                    continue
                if not isinstance(row, dict):
                    continue
                if "type" in row:
                    raw_type = row["type"]
                    if type(raw_type) not in (int, str):
                        continue
                    try:
                        type_id = int(raw_type)
                    except (ValueError, OverflowError):
                        continue
                    if type_id < 0:
                        continue
                    by_type[raw_type] = by_type[type_id] = row
                rows.append(row)
    except Exception as e:
        print(f"[InfiniCrafterLocal] runtime dump load failed for {path}: {e!r}")
    return rows, by_type


def runtime_projectile_lookup(type_id: Any) -> dict[str, Any]:
    try:
        found = RUNTIME_PROJECTILES_BY_TYPE.get(int(type_id))
        if isinstance(found, dict):
            return found
    except Exception:
        pass
    return {}


# One startup snapshot for the loaded Terraria/tModLoader mod set. These optional
# /infinidump files are factual input, never bundled personal data or authoring policy.
ITEMS_RUNTIME_DUMP_PATH = resolve_runtime_dump_path(
    DATA_DIR, "items_runtime_dump.jsonl", "INFINI_ITEMS_RUNTIME_DUMP", "INFINI_ITEMS_DUMP",
)
PROJECTILES_RUNTIME_DUMP_PATH = resolve_runtime_dump_path(
    DATA_DIR, "projectiles_runtime_dump.jsonl", "INFINI_PROJECTILES_RUNTIME_DUMP", "INFINI_PROJECTILES_DUMP",
)
RUNTIME_ITEMS = load_jsonl_index(ITEMS_RUNTIME_DUMP_PATH)[0]
RUNTIME_PROJECTILES_BY_TYPE = load_jsonl_index(PROJECTILES_RUNTIME_DUMP_PATH)[1]
