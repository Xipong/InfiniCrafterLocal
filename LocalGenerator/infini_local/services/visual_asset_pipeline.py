def _stable_rgb(seed: str) -> tuple[int, int, int]:
    h = hashlib.sha256(seed.encode("utf-8", "ignore")).digest()
    return (80 + h[0] % 150, 80 + h[1] % 150, 80 + h[2] % 150)


def generate_procedural_asset(
    data: dict[str, Any],
    role: str,
    *,
    variant: int = 0,
    canvas_size: int = 32,
    sprite_dir: Path,
    image_cls: Any,
    image_draw_cls: Any,
) -> str:
    role = str(role or "projectile").lower()
    canvas = int(canvas_size or 32)
    canvas = max(16, min(96, canvas))
    sprite_dir.mkdir(parents=True, exist_ok=True)
    seed = f"{data.get('id') or data.get('name') or 'item'}:{role}:{variant}"
    color = _stable_rgb(seed)
    accent = _stable_rgb(seed + ":accent")
    img = image_cls.new("RGBA", (canvas, canvas), (0, 0, 0, 0))
    d = image_draw_cls.Draw(img)
    pad = max(3, canvas // 8)
    cx = canvas // 2
    cy = canvas // 2
    if role == "impact":
        d.ellipse([pad, pad, canvas - pad, canvas - pad], fill=(*accent, 210))
        d.ellipse([pad * 2, pad * 2, canvas - pad * 2, canvas - pad * 2], fill=(255, 255, 255, 230))
    elif role == "child":
        r = max(2, canvas // 6)
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(*color, 235))
        d.line([cx - r * 2, cy, cx + r * 2, cy], fill=(*accent, 180), width=max(1, canvas // 16))
    elif role == "field":
        d.ellipse([pad, pad, canvas - pad, canvas - pad], outline=(*color, 230), width=max(2, canvas // 10))
        d.ellipse([pad * 2, pad * 2, canvas - pad * 2, canvas - pad * 2], outline=(*accent, 180), width=max(1, canvas // 16))
    elif role == "item":
        d.rounded_rectangle([pad, pad, canvas - pad, canvas - pad], radius=max(3, canvas // 6), fill=(*color, 235))
        d.line([pad * 2, canvas - pad * 2, canvas - pad * 2, pad * 2], fill=(*accent, 240), width=max(2, canvas // 10))
    else:
        d.polygon([(pad, cy), (canvas - pad, pad), (canvas - pad * 2, cy), (canvas - pad, canvas - pad)], fill=(*color, 240))
        d.line([pad, cy, canvas - pad, cy], fill=(*accent, 220), width=max(2, canvas // 12))
    name = f"{str(data.get('id') or 'generated')}_{role}_{variant}_{canvas}_procedural.png"
    safe = re.sub(r"[^a-zA-Z0-9_.-]+", "_", name)[:120]
    path = sprite_dir / safe
    img.save(path)
    return str(path)


def generate_procedural_sprite(data: dict[str, Any], *, variant: int = 0, sprite_dir: Path, image_cls: Any, image_draw_cls: Any) -> str:
    canvas = int(((data.get("visual") or {}).get("preferredCanvasSize") or 32) if isinstance(data.get("visual"), dict) else 32)
    return generate_procedural_asset(data, "item", variant=variant, canvas_size=canvas, sprite_dir=sprite_dir, image_cls=image_cls, image_draw_cls=image_draw_cls)
