def runtime_dump_candidates(data_dir: Path, filename: str) -> list[Path]:
    candidates: list[Path] = []

    # Optional packaged/dev location, useful while hacking locally, but should not
    # be populated in normal public zips.
    candidates.append(data_dir / "runtime_dumps" / filename)

    home = Path.home()
    user_profile = Path(env_str("USERPROFILE", str(home)))
    docs_roots = [
        home / "Documents",
        user_profile / "Documents",
        user_profile / "OneDrive" / "Documents",
        user_profile / "OneDrive" / "Документы",
        home / "Документы",
    ]
    for docs in docs_roots:
        candidates.append(docs / "My Games" / "Terraria" / "tModLoader" / "InfiniCrafterLocal" / filename)

    out: list[Path] = []
    seen: set[str] = set()
    for c in candidates:
        key = str(c).lower()
        if key not in seen:
            seen.add(key)
            out.append(c)
    return out


def resolve_runtime_dump_path(data_dir: Path, filename: str, explicit_env: str) -> Path:
    explicit = env_str(explicit_env)
    if explicit:
        return Path(explicit)
    candidates = runtime_dump_candidates(data_dir, filename)
    for c in candidates:
        if c.exists() or (c.parent / MANIFEST_NAME).exists() or (c.parent / MANIFEST_NAME).is_symlink():
            return c
    return candidates[0]


MANIFEST_NAME = "runtime_dump_manifest.json"
MANIFEST_SCHEMA = "infini.runtime-dump.v1"
MAX_MANIFEST_BYTES = 1024 * 1024
# File/count bounds are wire integer bounds, not memory allocation limits.
MAX_DUMP_BYTES = (1 << 63) - 1
MAX_DUMP_ROWS = (1 << 63) - 1
MAX_DUMP_ROW_BYTES = 16 * 1024 * 1024  # UTF-8 JSON plus LF/CRLF, matching the exporter.
MAX_DUMP_ROW_DEPTH = 64  # Same container-depth bound as the exporter JSON reader.


@dataclass(frozen=True)
class RuntimeDumpSnapshot:
    items: Mapping[int, dict[str, Any]]
    projectiles: Mapping[int, dict[str, Any]]
    provenance: dict[str, Any]
    modules: dict[str, str]

    def lookup(self, kind: Literal["item", "projectile"], type_id: Any, *,
               expected_full_name: Any = None, expected_modules: Any = None,
               expected_shoot: Any = None) -> dict[str, Any]:
        """Return isolated facts and provenance from this exact admitted snapshot."""
        index = {"item": self.items, "projectile": self.projectiles}[kind]
        try:
            if type(type_id) not in (int, str):
                return {}
            identity = int(type_id)
        except (ValueError, OverflowError):
            return {}
        if identity <= 0:
            return {}
        provenance = dict(self.provenance)
        provenance["compatibility"] = "unverified"
        if kind == "item":
            provenance["currentModSet"] = "unverified"
        if provenance["status"] == "invalid_snapshot":
            return {"type": identity, "unavailable": True, "runtimeDumpProvenance": provenance}
        found = index.get(identity)
        if not isinstance(found, dict):
            return {}
        actual_name = found.get("fullName")
        matched = []
        refusal = None
        expects_identity = isinstance(expected_full_name, str) and bool(expected_full_name)
        has_identity = isinstance(actual_name, str) and bool(actual_name)
        if (kind == "item" and not expects_identity) or (expects_identity and not has_identity):
            provenance.update(compatibility="unverified", reason=f"stable_{kind}_identity_unavailable")
            return {"type": identity, "unavailable": True, "runtimeDumpProvenance": provenance}
        if type(expected_shoot) is int and type(found.get("shoot")) is int and found["shoot"] != expected_shoot:
            refusal = "item_shoot_identity_mismatch"
        if isinstance(expected_full_name, str) and expected_full_name and actual_name:
            if actual_name != expected_full_name:
                refusal = kind + "_identity_mismatch"
            else:
                matched.append("identity")
        if isinstance(expected_modules, list):
            for module in expected_modules:
                if not isinstance(module, dict):
                    continue
                name, mvid = module.get("assembly"), module.get("mvid")
                observed = self.modules.get(name) if isinstance(name, str) else None
                if observed and isinstance(mvid, str) and mvid:
                    if observed != mvid:
                        refusal = "observed_module_mismatch"
                    elif "modules" not in matched:
                        matched.append("modules")
        if refusal:
            if kind == "item" and refusal == "observed_module_mismatch":
                provenance["currentModSet"] = "mismatch"
            provenance.update(compatibility="refused", reason=refusal)
            return {"type": identity, "unavailable": True, "runtimeDumpProvenance": provenance}
        if matched:
            provenance["compatibility"] = "matched_available_" + "_and_".join(matched)
        out = copy.deepcopy(found)
        out["runtimeDumpProvenance"] = provenance
        return out


def _bounded_bytes(path: Path, limit: int) -> bytes:
    root = path.parent.resolve()
    with _open_payload(root, root / path.name) as stream:
        data = stream.read(limit + 1)
    if len(data) > limit:
        raise ValueError("file_byte_bound")
    return data


def _manifest_for(path: Path) -> Path:
    return path if path.name == MANIFEST_NAME else path.parent / MANIFEST_NAME


def _snapshot_file(root: Path, relative: Any, snapshot_id: str, filename: str) -> Path:
    # A manifest is untrusted data: no absolute paths, traversal, other snapshot
    # IDs, platform-specific separators, or symlink escapes from its own root.
    expected = f"runtime_dump_snapshots/{snapshot_id}/{filename}"
    if not isinstance(relative, str) or relative != expected or "\\" in relative:
        raise ValueError("snapshot_path_invalid")
    parts = PurePosixPath(relative)
    if parts.is_absolute() or ".." in parts.parts:
        raise ValueError("snapshot_path_invalid")
    target = (root / relative).resolve()
    if not target.is_relative_to(root.resolve()):
        raise ValueError("snapshot_path_escape")
    return target


@contextmanager
def _open_payload(root: Path, path: Path):
    """Pin each directory while opening; never follow a swapped payload symlink."""
    if os.open in os.supports_dir_fd and hasattr(os, "O_NOFOLLOW"):
        descriptors = []
        try:
            current = os.open(root, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
            descriptors.append(current)
            parts = path.relative_to(root).parts
            for component in parts[:-1]:
                current = os.open(component, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=current)
                descriptors.append(current)
            fd = os.open(parts[-1], os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=current)
            try:
                stream = os.fdopen(fd, "rb")
            except BaseException:
                os.close(fd)
                raise
            with stream:
                if not stat.S_ISREG(os.fstat(stream.fileno()).st_mode):
                    raise ValueError("snapshot_payload_not_regular")
                yield stream
        finally:
            for descriptor in reversed(descriptors):
                os.close(descriptor)
    else:
        # Windows lacks openat; validate the resolved path and regular-file
        # identity around open. Facts are copied and hashed, never read later.
        before = path.stat()
        with path.open("rb") as stream:
            opened = os.fstat(stream.fileno())
            if (not stat.S_ISREG(opened.st_mode) or not path.resolve().is_relative_to(root)
                    or not os.path.samestat(before, opened) or not os.path.samestat(path.stat(), opened)):
                raise ValueError("snapshot_payload_changed")
            yield stream


def _validate_row_depth(row: dict[str, Any]) -> None:
    # Decoder recursion guards vary across Python versions. Limit admitted
    # container depth explicitly, also protecting later deepcopy/context use.
    stack = [iter(row.values())]
    while stack:
        try:
            value = next(stack[-1])
        except StopIteration:
            stack.pop()
            continue
        if isinstance(value, (dict, list)):
            if len(stack) >= MAX_DUMP_ROW_DEPTH:
                raise ValueError("snapshot_record_depth_bound")
            stack.append(iter(value.values()) if isinstance(value, dict) else iter(value))


def _verified_rows(root: Path, path: Path, descriptor: dict[str, Any],
                   store: RuntimeDumpIndex, kind: int) -> Mapping[int, dict[str, Any]]:
    size, count, errors = (descriptor.get(k) for k in ("bytes", "rows", "unavailableRows"))
    if type(size) is not int or type(count) is not int or type(errors) is not int:
        raise ValueError("snapshot_counts_invalid")
    if not (0 <= size <= MAX_DUMP_BYTES and 0 <= errors <= count <= MAX_DUMP_ROWS):
        raise ValueError("snapshot_counts_invalid")
    digest = descriptor.get("sha256")
    if not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest):
        raise ValueError("snapshot_hash_invalid")
    observed_bytes = observed_rows = observed_errors = 0
    hasher = hashlib.sha256()
    with _open_payload(root, path) as stream:
        if os.fstat(stream.fileno()).st_size != size:
            raise ValueError("snapshot_size_mismatch")
        while True:
            line = stream.readline(min(MAX_DUMP_ROW_BYTES, size - observed_bytes) + 1)
            if not line:
                break
            if len(line) > MAX_DUMP_ROW_BYTES or observed_bytes + len(line) > size:
                raise ValueError("snapshot_row_or_byte_bound")
            if observed_rows >= count:
                raise ValueError("snapshot_row_bound")
            hasher.update(line)
            row = strict_json.loads(line.decode("utf-8"))
            if not isinstance(row, dict) or type(row.get("type")) is not int or row["type"] < 0:
                raise ValueError("snapshot_record_invalid")
            _validate_row_depth(row)
            store.add(kind, row["type"], line)
            observed_bytes += len(line)
            observed_rows += 1
            observed_errors += row.get("unavailable") is True
    if observed_bytes != size or hasher.hexdigest() != digest:
        raise ValueError("snapshot_hash_mismatch")
    if observed_rows != count or observed_errors != errors:
        raise ValueError("snapshot_counts_mismatch")
    return store.rows(kind, observed_rows)

def load_runtime_dump_snapshot(items_path: Path, projectiles_path: Path) -> RuntimeDumpSnapshot:
    manifests = [_manifest_for(path) for path in (items_path, projectiles_path)]
    if not any(path.exists() or path.is_symlink() for path in manifests):
        if any(path.exists() or path.is_symlink() for path in (items_path, projectiles_path)):
            return RuntimeDumpSnapshot({}, {}, {"status": "invalid_snapshot", "reason": "snapshot_manifest_required"}, {})
        return RuntimeDumpSnapshot({}, {}, {"status": "absent"}, {})
    store = None
    admitted = False
    try:
        if manifests[0].resolve() != manifests[1].resolve():
            raise ValueError("configured_pair_manifest_mismatch")
        path = manifests[0]
        for configured, kind in ((items_path, "items"), (projectiles_path, "projectiles")):
            if configured.name not in (MANIFEST_NAME, f"{kind}_runtime_dump.jsonl"):
                raise ValueError("configured_payload_does_not_name_manifest_pair")
        root = path.parent.resolve()
        if not path.resolve().is_relative_to(root):
            raise ValueError("manifest_path_escape")
        manifest = strict_json.loads(_bounded_bytes(path, MAX_MANIFEST_BYTES).decode("utf-8"))
        if not isinstance(manifest, dict) or manifest.get("schema") != MANIFEST_SCHEMA:
            raise ValueError("manifest_schema_unsupported")
        snapshot_id = manifest.get("snapshotId")
        if not isinstance(snapshot_id, str) or not re.fullmatch(r"[0-9a-f]{32}", snapshot_id):
            raise ValueError("snapshot_id_invalid")
        captured = manifest.get("capturedAtUtc")
        if not isinstance(captured, str) or len(captured) > 64 or datetime.fromisoformat(captured.replace("Z", "+00:00")).utcoffset() != timedelta(0):
            raise ValueError("snapshot_timestamp_invalid")
        files = manifest.get("files")
        if not isinstance(files, dict) or set(files) != {"items", "projectiles"}:
            raise ValueError("snapshot_pair_invalid")
        loaded = {}
        store = RuntimeDumpIndex()
        for kind_id, kind in enumerate(("items", "projectiles")):
            descriptor = files[kind]
            if not isinstance(descriptor, dict):
                raise ValueError("snapshot_descriptor_invalid")
            target = _snapshot_file(root, descriptor.get("path"), snapshot_id, f"{kind}_runtime_dump.jsonl")
            loaded[kind] = _verified_rows(root, target, descriptor, store, kind_id)
        environment = manifest.get("environment")
        if not isinstance(environment, dict) or not isinstance(environment.get("mods"), list):
            raise ValueError("snapshot_environment_invalid")
        modules: dict[str, str] = {}
        module_rows = [environment.get("tModLoader"), environment.get("exporter")]
        module_rows += [mod.get("module") for mod in environment["mods"] if isinstance(mod, dict)]
        for module in module_rows:
            if isinstance(module, dict) and isinstance(module.get("assembly"), str) and isinstance(module.get("mvid"), str):
                name, mvid = module["assembly"], module["mvid"]
                if name in modules and modules[name] != mvid:
                    raise ValueError("snapshot_module_identity_conflict")
                modules[name] = mvid
        store.seal()
        admitted = True
        return RuntimeDumpSnapshot(loaded["items"], loaded["projectiles"],
            {"status": "verified_snapshot", "snapshotId": snapshot_id, "capturedAtUtc": captured}, modules)
    except (OSError, ValueError, TypeError, KeyError, UnicodeError, sqlite3.Error):
        # Admit the complete pair or neither file. Never mix captures or expose manifest content.
        return RuntimeDumpSnapshot({}, {}, {"status": "invalid_snapshot", "reason": "manifest_or_pair_validation_failed"}, {})

    finally:
        if store is not None and not admitted:
            store.close()


# One startup snapshot; a newly exported pair requires a generator restart.
# Integrity is not live-runtime compatibility or proof of complete AI behavior.
reject_retired_config(os.environ)
ITEMS_RUNTIME_DUMP_PATH = resolve_runtime_dump_path(
    DATA_DIR, "items_runtime_dump.jsonl", "INFINI_ITEMS_RUNTIME_DUMP",
)
PROJECTILES_RUNTIME_DUMP_PATH = resolve_runtime_dump_path(
    DATA_DIR, "projectiles_runtime_dump.jsonl", "INFINI_PROJECTILES_RUNTIME_DUMP",
)
RUNTIME_DUMP_SNAPSHOT = load_runtime_dump_snapshot(ITEMS_RUNTIME_DUMP_PATH, PROJECTILES_RUNTIME_DUMP_PATH)
if RUNTIME_DUMP_SNAPSHOT.provenance["status"] == "invalid_snapshot":
    print("[InfiniCrafterLocal] runtime dump: " + RUNTIME_DUMP_SNAPSHOT.provenance["reason"]
          + "; export a current /infinidump manifest pair and restart the generator")
